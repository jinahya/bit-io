    private static final int PREFIX_SIZE = 3;

    private static final int PREFIX = 0x5; // 101

    private static final int SUFFIX_SIZE = 5;

    private static final int SUFFIX = 0x13; // 10011

    interface Write {

        void write(BitOutput output) throws IOException;
    }

    interface Read {

        String read(BitInput input) throws IOException;
    }

    private static final class Case {

        Case(final String name, final Write write, final Read read) {
            this.name = name;
            this.write = write;
            this.read = read;
        }

        final String name;

        final Write write;

        final Read read;
    }

    private static final List<Case> CASES = new ArrayList<>();

    private static void add(final String name, final Write write, final Read read) {
        CASES.add(new Case(name, write, read));
    }

