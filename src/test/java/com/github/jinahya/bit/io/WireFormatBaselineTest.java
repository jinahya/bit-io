    private static <T> void addObject(final String name, final BitWriter<? super T> writer,
                                      final BitReader<? extends T> reader, final T value) {
        add(name, o -> o.writeObject(writer, value), i -> describe(i.readObject(reader)));
    }

    private static void addLong(final String name, final LongBitWriter writer, final LongBitReader reader,
                                final long... values) {
        for (final long value : values) {
            add(name + "-" + value, o -> o.writeLong(writer, value), i -> Long.toString(i.readLong(reader)));
        }
    }

    // -----------------------------------------------------------------------------------------------------------------
    private static String floatBits(final float value) {
        return "f:" + Integer.toHexString(Float.floatToRawIntBits(value));
    }

    private static String doubleBits(final double value) {
        return "d:" + Long.toHexString(Double.doubleToRawLongBits(value));
    }

    private static String describe(final Object value) {
        if (value instanceof byte[]) {
            return "bytes:" + hex((byte[]) value);
        }
        if (value instanceof long[]) {
            return "longs:" + Arrays.toString((long[]) value);
        }
        if (value instanceof String) {
            return "string:" + escape((String) value);
        }
        return String.valueOf(value);
    }

    private static String escape(final String value) {
        final StringBuilder builder = new StringBuilder();
        for (int i = 0; i < value.length(); i++) {
            final char c = value.charAt(i);
            if (c >= 0x20 && c < 0x7F && c != '\\') {
                builder.append(c);
            } else {
                builder.append(String.format("\\u%04x", (int) c));
            }
        }
        return builder.toString();
    }

    private static String hex(final byte[] bytes) {
        final StringBuilder builder = new StringBuilder();
        for (final byte b : bytes) {
            builder.append(String.format("%02x", b & 0xFF));
        }
        return builder.toString();
    }

    private static byte[] bytes(final String hex) {
        final byte[] bytes = new byte[hex.length() / 2];
        for (int i = 0; i < bytes.length; i++) {
            bytes[i] = (byte) Integer.parseInt(hex.substring(i * 2, i * 2 + 2), 16);
        }
        return bytes;
    }

    /**
     * Writes specified case, framed, and returns the bytes.
     */
    private static byte[] write(final Case c) throws IOException {
        final ByteArrayOutputStream bytes = new ByteArrayOutputStream();
        final BitOutput output = new DefaultBitOutput(new StreamByteOutput(bytes));
        output.writeUnsignedInt(PREFIX_SIZE, PREFIX);
        c.write.write(output);
        output.writeUnsignedInt(SUFFIX_SIZE, SUFFIX);
        output.align(1);
        return bytes.toByteArray();
    }

    /**
     * Reads specified case, framed, from specified bytes and returns its decoded value, or a description of a framing
     * error.
     */
    private static String read(final Case c, final byte[] bytes) throws IOException {
        final BitInput input = new DefaultBitInput(new ArrayByteInput(bytes));
        final int prefix = input.readUnsignedInt(PREFIX_SIZE);
        final String value = c.read.read(input);
        final int suffix = input.readUnsignedInt(SUFFIX_SIZE);
        if (prefix != PREFIX || suffix != SUFFIX) {
            return "framing-error(prefix=" + prefix + ",suffix=" + suffix + "):" + value;
        }
        return value;
    }

    private static Map<String, String[]> baseline() throws IOException {
        final Map<String, String[]> baseline = new LinkedHashMap<>();
        try (InputStream stream = WireFormatBaselineTest.class.getResourceAsStream(BASELINE)) {
            assertNotNull(stream, "missing resource " + BASELINE);
            final BufferedReader lines = new BufferedReader(new InputStreamReader(stream, StandardCharsets.UTF_8));
            for (String line; (line = lines.readLine()) != null; ) {
                if (line.isEmpty() || line.startsWith("#")) {
                    continue;
                }
                final String[] fields = line.split("\t", -1);
                baseline.put(fields[0], new String[]{fields[1], fields[2]});
            }
        }
        return baseline;
    }

    // -----------------------------------------------------------------------------------------------------------------

    /**
     * Prints the baseline for the bit-io on the class path; run against the released 4.2.1 jar only.
     *
     * @param args ignored.
     * @throws IOException if an I/O error occurs.
     */
    public static void main(final String... args) throws IOException {
        System.out.println("# name\thex (framed: 3-bit prefix 101, value, 5-bit suffix 10011, align(1))\tdecoded");
        for (final Case c : CASES) {
            final byte[] bytes = write(c);
            System.out.println(c.name + "\t" + hex(bytes) + "\t" + read(c, bytes));
        }
    }

    @Test
    void everyCaseHasABaselineAndNoBaselineIsStale() throws IOException {
        final List<String> names = new ArrayList<>();
        for (final Case c : CASES) {
            names.add(c.name);
        }
        assertEquals(new ArrayList<>(baseline().keySet()), names);
    }

    @TestFactory
    List<DynamicTest> writesAndReadsTheReleasedBytes() throws IOException {
        final Map<String, String[]> baseline = baseline();
        final List<DynamicTest> tests = new ArrayList<>();
        for (final Case c : CASES) {
            tests.add(DynamicTest.dynamicTest(c.name, () -> {
                final String[] expected = baseline.get(c.name);
                assertNotNull(expected, "no baseline for " + c.name);
                assertEquals(expected[0], hex(write(c)), "bytes written");
                assertEquals(expected[1], read(c, bytes(expected[0])), "value read from the released bytes");
            }));
        }
        return tests;
    }
