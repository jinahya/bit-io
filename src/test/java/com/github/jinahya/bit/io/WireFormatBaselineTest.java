/**
 * Pins the wire format of every codec to the bytes written by the <em>released</em> bit-io 4.2.1.
 *
 * <p>Each case writes one value framed by a {@value #PREFIX_SIZE}-bit prefix and a {@value #SUFFIX_SIZE}-bit suffix,
 * so values start and end at non-octet offsets and a change in the number of bits a codec consumes is caught. The
 * expected bytes and decoded values are in {@value #BASELINE}, generated by running {@link #main(String[])} against the
 * released {@code bit-io-4.2.1.jar}:</p>
 * <pre>{@code
 * javac -cp bit-io-4.2.1.jar:junit-jupiter-api.jar -d out WireFormatBaselineTest.java
 * java -cp bit-io-4.2.1.jar:junit-jupiter-api.jar:out com.github.jinahya.bit.io.WireFormatBaselineTest > wire-baseline-4.2.1.tsv
 * }</pre>
 *
 * <p>4.2.1 wrote the expected bytes and the current code reads them (old writer, new reader); the current code must
 * also write identical bytes, which 4.2.1 reads by construction (new writer, old reader). Never regenerate the baseline
 * from the current code.</p>
 */
